# Uploads new or changed FBX exports in assets/export/<Kind>/<Shape>.fbx to Roblox as Model
# assets via the Open Cloud Assets API, records the IDs in assets/asset-ids.json and regenerates
# src/shared/Cosmetics/AssetIds.luau.
#
# Usage:  powershell -ExecutionPolicy Bypass -File tools/upload-assets.ps1 [-Force]
# Needs:  .roblox-api-key (Assets read+write) and assets/upload.config.json:
#         { "creatorType": "user" | "group", "creatorId": "123" }
param([switch]$Force)

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$exportDir = Join-Path $root "assets\export"
$idsPath = Join-Path $root "assets\asset-ids.json"
$configPath = Join-Path $root "assets\upload.config.json"
$keyPath = Join-Path $root ".roblox-api-key"
$luauPath = Join-Path $root "src\shared\Cosmetics\AssetIds.luau"
$api = "https://apis.roblox.com/assets/v1"

if (-not (Test-Path $keyPath)) { throw "Missing .roblox-api-key" }
if (-not (Test-Path $configPath)) { throw "Missing assets/upload.config.json" }
$config = Get-Content $configPath -Raw | ConvertFrom-Json

# The key goes to curl through a header file so it never appears on a command line.
$headerFile = [IO.Path]::GetTempFileName()
$key = (Get-Content $keyPath -Raw).Trim()
[IO.File]::WriteAllText($headerFile, "x-api-key: $key`n")
$key = $null

function Invoke-Curl([string[]]$curlArgs) {
	$out = & curl.exe -s -w "`n%{http_code}" -H "@$headerFile" @curlArgs
	$lines = ($out -join "`n") -split "`n"
	$code = [int]$lines[-1]
	$body = ($lines[0..($lines.Length - 2)] -join "`n")
	if ($code -lt 200 -or $code -ge 300) { throw "HTTP $code : $body" }
	return $body | ConvertFrom-Json
}

function Wait-Operation($op) {
	$id = ($op.path -split "/")[-1]
	for ($i = 0; $i -lt 60; $i++) {
		if ($op.done) {
			if ($op.error) { throw "Upload failed: $($op.error | ConvertTo-Json -Compress)" }
			return $op.response
		}
		Start-Sleep -Seconds 2
		$op = Invoke-Curl @("$api/operations/$id")
	}
	throw "Timed out waiting for operation $id"
}

$ids = @{}
if (Test-Path $idsPath) {
	(Get-Content $idsPath -Raw | ConvertFrom-Json).PSObject.Properties | ForEach-Object {
		$ids[$_.Name] = @{ assetId = [string]$_.Value.assetId; hash = [string]$_.Value.hash }
	}
}

$creator = if ($config.creatorType -eq "group") { @{ groupId = [string]$config.creatorId } } else { @{ userId = [string]$config.creatorId } }

try {
	foreach ($file in Get-ChildItem $exportDir -Recurse -Filter *.fbx) {
		$kind = $file.Directory.Name
		$shape = $file.BaseName
		$name = "$kind/$shape"
		$hash = (Get-FileHash $file.FullName -Algorithm SHA256).Hash
		$entry = $ids[$name]
		if ($entry -and $entry.hash -eq $hash -and -not $Force) { Write-Host "unchanged  $name"; continue }

		$requestFile = [IO.Path]::GetTempFileName()
		if ($entry) {
			$request = @{ assetId = $entry.assetId }
			$method = "PATCH"; $url = "$api/assets/$($entry.assetId)"
		} else {
			$request = @{
				assetType = "Model"
				displayName = "Monopoly $kind $shape"
				description = "Monopoly board game $($kind.ToLower()) model."
				creationContext = @{ creator = $creator }
			}
			$method = "POST"; $url = "$api/assets"
		}
		[IO.File]::WriteAllText($requestFile, ($request | ConvertTo-Json -Depth 5 -Compress))
		try {
			$op = Invoke-Curl @("-X", $method, $url, "-F", "request=<$requestFile;type=application/json", "-F", "fileContent=@$($file.FullName);type=model/fbx")
		} finally {
			Remove-Item $requestFile -ErrorAction SilentlyContinue
		}
		$result = Wait-Operation $op
		$assetId = if ($result.assetId) { [string]$result.assetId } else { $entry.assetId }
		$ids[$name] = @{ assetId = $assetId; hash = $hash }
		Write-Host "uploaded   $name -> $assetId"

		# Saved after each upload so a later failure doesn't lose earlier IDs.
		$ordered = [ordered]@{}
		foreach ($k in ($ids.Keys | Sort-Object)) { $ordered[$k] = [ordered]@{ assetId = $ids[$k].assetId; hash = $ids[$k].hash } }
		[IO.File]::WriteAllText($idsPath, ($ordered | ConvertTo-Json -Depth 5))
	}
} finally {
	Remove-Item $headerFile -ErrorAction SilentlyContinue
}

# Regenerate AssetIds.luau: Kind -> Shape -> asset ID.
$byKind = @{}
foreach ($k in $ids.Keys) {
	$kind, $shape = $k -split "/"
	if (-not $byKind[$kind]) { $byKind[$kind] = @{} }
	$byKind[$kind][$shape] = $ids[$k].assetId
}
$lines = @("--!strict", "-- Generated by tools/upload-assets.ps1 from assets/asset-ids.json. Do not edit.", "", "local AssetIds: { [string]: { [string]: number } } = {")
foreach ($kind in ($byKind.Keys | Sort-Object)) {
	$lines += "`t$kind = {"
	foreach ($shape in ($byKind[$kind].Keys | Sort-Object)) { $lines += "`t`t$shape = $($byKind[$kind][$shape])," }
	$lines += "`t},"
}
$lines += @("}", "", "return AssetIds", "")
New-Item -ItemType Directory -Force (Split-Path $luauPath) | Out-Null
[IO.File]::WriteAllText($luauPath, ($lines -join "`n"), (New-Object Text.UTF8Encoding($false)))
Write-Host "wrote      src/shared/Cosmetics/AssetIds.luau"
